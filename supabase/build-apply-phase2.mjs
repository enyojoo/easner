#!/usr/bin/env node
/**
 * Writes supabase/apply-phase2.sql: the Phase 2 migrations (20261115*) in one transaction, for a hosted project that
 * already ran the earlier setup (hosted-setup.sql or `supabase db push` up to 20261114*). Re-run after editing one:
 *
 *   node supabase/build-apply-phase2.mjs
 *
 * hosted-setup.sql and fix-public-access.sql are not regenerated (they carry the owner's email and are out of date by design).
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const dir = path.join(here, "migrations")
const files = fs.readdirSync(dir).filter((f) => /^20261115.*\.sql$/.test(f)).sort()

const parts = [
  "-- Apply Phase 2 to an existing easner-website project (generated by supabase/build-apply-phase2.mjs; do not edit).",
  "-- Run once in the Supabase SQL editor, after the earlier setup. It is one transaction: it applies fully or not at all.",
  `-- Contains: ${files.join(", ")}`,
  "",
  "begin;",
  "",
]
for (const file of files) {
  parts.push(`-- >>> ${file}`, fs.readFileSync(path.join(dir, file), "utf8").trim(), "")
}
parts.push("commit;", "")
fs.writeFileSync(path.join(here, "apply-phase2.sql"), parts.join("\n"))
console.log(`wrote supabase/apply-phase2.sql from ${files.length} migration(s)`)
