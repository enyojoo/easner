#!/usr/bin/env node
/**
 * Writes supabase/apply-phase4b.sql: the Phase 4B migrations (20261118*) in one transaction, for a hosted project that
 * already ran Phase 2 (apply-phase2.sql). Re-run after editing one:
 *
 *   node supabase/build-apply-phase4b.mjs
 *
 * hosted-setup.sql and fix-public-access.sql are not regenerated (they carry the owner's email and are out of date by design).
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const dir = path.join(here, "migrations")
const files = fs.readdirSync(dir).filter((f) => /^20261118.*\.sql$/.test(f)).sort()

const parts = [
  "-- Apply Phase 4B to an existing easner-website project (generated by supabase/build-apply-phase4b.mjs; do not edit).",
  "-- Run once in the Supabase SQL editor, after the earlier setup. It is one transaction: it applies fully or not at all.",
  `-- Contains: ${files.join(", ")}`,
  "",
  "begin;",
  "",
]
for (const file of files) {
  parts.push(`-- >>> ${file}`, fs.readFileSync(path.join(dir, file), "utf8").trim(), "")
}
parts.push("commit;", "")
fs.writeFileSync(path.join(here, "apply-phase4b.sql"), parts.join("\n"))
console.log(`wrote supabase/apply-phase4b.sql from ${files.length} migration(s)`)
