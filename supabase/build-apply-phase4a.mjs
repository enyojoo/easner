#!/usr/bin/env node
/**
 * Writes supabase/apply-phase4a.sql: the Phase 4A migrations (20261117*) in one transaction, for a hosted project that
 * already ran everything up to Phase 3 (apply-phase2.sql and the later migrations). Re-run after editing one:
 *
 *   node supabase/build-apply-phase4a.mjs
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const dir = path.join(here, "migrations")
const files = fs.readdirSync(dir).filter((f) => /^20261117.*\.sql$/.test(f)).sort()

const parts = [
  "-- Apply Phase 4A (analytics rollups) to an existing easner-website project (generated by supabase/build-apply-phase4a.mjs; do not edit).",
  "-- Run once in the Supabase SQL editor, after apply-phase2.sql and the 20261115/20261116 migrations. One transaction: all or nothing.",
  `-- Contains: ${files.join(", ")}`,
  "",
  "begin;",
  "",
]
for (const file of files) {
  parts.push(`-- >>> ${file}`, fs.readFileSync(path.join(dir, file), "utf8").trim(), "")
}
parts.push("commit;", "")
fs.writeFileSync(path.join(here, "apply-phase4a.sql"), parts.join("\n"))
console.log(`wrote supabase/apply-phase4a.sql from ${files.length} migration(s)`)
