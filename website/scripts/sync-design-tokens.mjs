#!/usr/bin/env node
/**
 * Sync design tokens from the Easner design system (easnerbanking/design-system).
 * Usage: node scripts/sync-design-tokens.mjs
 *
 * Writes app/design-tokens.css:
 * - :root with every token except fonts, Tailwind-namespaced tokens and prose-only tokens
 * - .surface-product restoring the shared semantic colours for product screens shown on the website
 * - @theme with radius, shadow and ease values (Tailwind namespaces, set by value to avoid self-reference)
 * - @theme inline mapping each colour token to a Tailwind colour (text-web-body, bg-web-band, …)
 */

import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const WEBSITE_ROOT = path.resolve(__dirname, "..")
const DESIGN_SYSTEM = path.resolve(process.env.EASNER_DS_PATH || path.resolve(WEBSITE_ROOT, "../../easnerbanking/design-system"))
const SOURCE = path.join(DESIGN_SYSTEM, "components/tokens.css")
const OUT = path.join(WEBSITE_ROOT, "app/design-tokens.css")

/** Tailwind theme namespaces: emitted under @theme by value, not in :root. */
const THEME_NAMESPACES = ["radius-", "shadow-", "ease-"]
/** Dropped: fonts load through next/font and geist; haptic and spring tokens are prose, not CSS. */
const DROPPED = [/^font-/, /^haptic-/, /^spring-/]

if (!fs.existsSync(SOURCE)) {
  console.error(`Design tokens not found at ${SOURCE}. Set EASNER_DS_PATH to the design-system folder.`)
  process.exit(1)
}

const css = fs.readFileSync(SOURCE, "utf8")
const rootMatch = css.match(/:root\s*\{([\s\S]*?)\n\}/)
if (!rootMatch) {
  console.error("No :root block found in tokens.css")
  process.exit(1)
}

const tokens = []
for (const line of rootMatch[1].split("\n")) {
  const match = line.trim().match(/^--([a-z0-9-]+)\s*:\s*(.+?);?$/i)
  if (match) tokens.push({ name: match[1], value: match[2].replace(/;$/, "").trim() })
}
const byName = new Map(tokens.map((token) => [token.name, token.value]))

function isColourValue(value, seen = new Set()) {
  if (/^(#|hsla?\(|rgba?\(|oklch\(|color-mix\()/i.test(value)) return true
  const ref = value.match(/^var\(--([a-z0-9-]+)\)$/i)
  if (!ref || seen.has(ref[1]) || !byName.has(ref[1])) return false
  seen.add(ref[1])
  return isColourValue(byName.get(ref[1]), seen)
}

const kept = tokens.filter(({ name }) => !DROPPED.some((pattern) => pattern.test(name)))
const themed = kept.filter(({ name }) => THEME_NAMESPACES.some((prefix) => name.startsWith(prefix)))
const root = kept.filter((token) => !themed.includes(token))
const colours = root.filter(({ value }) => isColourValue(value))
/** Shared semantic colours (background, card, border …). The website points some at web-* tokens; product screens restore them. */
const semantic = colours.filter(({ name }) => !/^(web|brand|app)-/.test(name))

/** Resolve a themed value whose var() points at another token, so @theme never references itself. */
function resolve(value) {
  return value.replace(/var\(--([a-z0-9-]+)\)/gi, (whole, name) => (byName.has(name) ? resolve(byName.get(name)) : whole))
}

const out = [
  "/* Generated by scripts/sync-design-tokens.mjs from easnerbanking/design-system/components/tokens.css.",
  " * Do not edit by hand: change the design system, then run `npm run sync:tokens`. */",
  "",
  ":root {",
  ...root.map(({ name, value }) => `  --${name}: ${value};`),
  "}",
  "",
  "/* Product screens on the website (Business, Office) sit inside .surface-product to get the product's own ivory canvas. */",
  ".surface-product {",
  ...semantic.map(({ name, value }) => `  --${name}: ${value};`),
  "}",
  "",
  "@theme {",
  ...themed.map(({ name, value }) => `  --${name}: ${resolve(value)};`),
  "}",
  "",
  "@theme inline {",
  ...colours.map(({ name }) => `  --color-${name}: var(--${name});`),
  "}",
  "",
].join("\n")

fs.writeFileSync(OUT, out)
console.log(
  `Wrote ${path.relative(WEBSITE_ROOT, OUT)}: ${root.length} tokens, ${themed.length} theme values, ${colours.length} colours.`,
)
